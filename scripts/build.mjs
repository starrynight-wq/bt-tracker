/*
 * Build script for bt-tracker.
 *
 * Generates:
 *   src/dashboard-html.js  - public/dashboard.html embedded as an ES module
 *                            (used by src/worker.js and src/worker-bundle.js)
 *   src/worker-bundle.js   - single-file Cloudflare Worker bundle for projects
 *                            deployed by pasting code into the dashboard UI
 *
 * Run with:  npm run build
 */

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));

const read = (rel) => readFile(path.join(ROOT, rel), 'utf8');
const write = (rel, content) => writeFile(path.join(ROOT, rel), content, 'utf8');

/* Strip ES module syntax so files can be concatenated into one worker script. */
function stripModuleCode(src, { keepDefault = false } = {}) {
  let out = src;
  // import x from '...' / import { a, b } from '...' (single or multi line)
  out = out.replace(/^import\s+[\s\S]*?from\s+['"][^'"]+['"];?[ \t]*$/gm, '');
  // side-effect imports: import '...'
  out = out.replace(/^import\s+['"][^'"]+['"];?[ \t]*$/gm, '');
  // export { a, b };
  out = out.replace(/^export\s*\{[^}]*\};?[ \t]*$/gm, '');
  // export class/function/const/let/var -> plain declarations
  out = out.replace(/^export\s+(?=(?:async\s+)?(?:class|function|const|let|var)\b)/gm, '');
  if (!keepDefault) out = out.replace(/^export\s+default\s+/gm, '');
  return out.replace(/\n{3,}/g, '\n\n').trim();
}

async function build() {
  const dashboardHtml = await read('public/dashboard.html');

  /* 1. Dashboard HTML module (JSON string => no template-literal escaping issues) */
  const dashboardModule =
    '/* AUTO-GENERATED FILE - run `npm run build` to regenerate from public/dashboard.html. */\n' +
    '/* eslint-disable */\n' +
    'export const DASHBOARD_HTML = ' + JSON.stringify(dashboardHtml) + ';\n';
  await write('src/dashboard-html.js', dashboardModule);

  /* 2. Single-file worker bundle */
  const banner = `/*
 * bt-tracker - Single-file Cloudflare Worker bundle.
 *
 * Deploy WITHOUT the CLI:
 *   1. Copy the entire contents of this file.
 *   2. Cloudflare dashboard -> Workers & Pages -> Create -> Create a Worker
 *   3. Paste this code into the editor, click Deploy.
 *   4. Add KV namespace bindings: BT_TORRENTS, BT_TRACKERS, BT_ALERTS
 *   5. Add environment variables (optional): BT_INTERVAL, BT_MIN_INTERVAL, BT_TRACKER_ID
 *   6. Open https://<your-worker>.workers.dev/dashboard
 *
 * AUTO-GENERATED by scripts/build.mjs from:
 *   src/bencode.js + src/store.js + src/tracker.js + src/worker.js + public/dashboard.html
 * Do not edit this file by hand.
 */

'use strict';
`;

  const sections = [
    ['bencode.js', await read('src/bencode.js')],
    ['store.js', await read('src/store.js')],
    ['tracker.js', await read('src/tracker.js')],
    ['worker.js', await read('src/worker.js')]
  ];

  const parts = [banner];
  for (const [name, source] of sections) {
    const isWorker = name === 'worker.js';
    parts.push(`/* ============================ ${name} (generated) ============================ */\n`);
    parts.push(stripModuleCode(source, { keepDefault: isWorker }));
    parts.push('\n');
  }
  parts.push('/* ============================ dashboard-html.js (generated) ============================ */\n');
  parts.push('const DASHBOARD_HTML = ' + JSON.stringify(dashboardHtml) + ';\n');

  await write('src/worker-bundle.js', parts.join('\n'));
  console.log('[build] wrote src/dashboard-html.js and src/worker-bundle.js');
}

build().catch((e) => {
  console.error('[build] failed:', e);
  process.exit(1);
});
